/// <summary>
/// Russische Questnamen -> Zeilen-Ids im Quest-Blatt.
///
/// Warum es das braucht: die Quest-ART (Hauptszenario / Klasse / Nebenauftrag)
/// kommt aus einem Namensvergleich zwischen der Kartenmarkierung und dem
/// Quest-Blatt. Das Blatt liefert in dieser Installation ENGLISCH, die
/// Markierung traegt den GERENDERTEN Namen (2026-09-14: russisch) - der
/// Vergleich findet deshalb nichts, und die Art schweigt bei jeder Quest
/// (Meldung der Spielerin, #84). Der Name kennt keine Sprache, die Id schon:
/// ueber diesen Rueckweg wird die Zeile gefunden und aus ihrer Journal-Sektion
/// die Art bestimmt.
///
/// Quelle der Namen ist die Uebersetzungsdatei des Rusik selbst
/// (github.com/xivrus/xiv_ru_weblate, exd/Quest/ru.xlf, abgerufen am
/// 2026-09-14) - also genau die Woerter, die im russischen Spiel stehen.
/// Genommen wird das erste Feld des Ziels (der Kurzname vor dem ersten
/// Tabulator); die Regie-Anhaenge dahinter gehoeren nicht in eine Ansage.
///
/// Nicht enthalten: Eintraege ohne Uebersetzung (dort steht der Name weiter
/// lateinisch - die englische Suche findet ihn ohnehin). Sie enden in
/// "unbekannt" und damit im Schweigen wie bisher - nie in einer falschen
/// Ansage.
///
/// Mehrdeutige Namen stehen mit ALLEN Zeilen-Ids hier. Der
/// QuestMarkerService liest jede brauchbare Zeile; bei widerspruechlichen
/// Arten oder Stufen bleibt die Angabe unbekannt. Zeilen ohne Journal-Gattung
/// ("Ungueltige Kategorie") werden dabei uebersprungen.
/// Die ZWEITE Richtung (Zeilen-Id -> russischer Name, <see cref="QuestName"/>)
/// gibt es seit 6.08.88 fuer Ansagen, die die Zeile schon kennen: das Objekt
/// haengt im Blatt an einer Quest-Zeile, nicht am Namen. Vorher stand dort der
/// englische Name aus dem Blatt - gehoert wurde "Цель для To Catch a Poacher"
/// (Meldung 2026-09-16), waehrend im Journal "Поймать браконьера" steht.
/// Beide Tabellen kommen aus DERSELBEN Uebersetzungsdatei, es gibt also keinen
/// zweiten Stand, der driften koennte.
///
/// 1912 Namen, davon 73 mehrdeutig, 1993 Zeilen mit
/// Uebersetzung; generiert, nicht von Hand pflegen.
/// </summary>
