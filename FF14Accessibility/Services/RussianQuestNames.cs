    /// <summary>Zeilen-Ids zum gerenderten russischen Questnamen. Leer, wenn
    /// der Name unbekannt ist; mehrere Eintraege bei mehrdeutigen Namen.</summary>
    public static uint[] QuestIds(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return Array.Empty<uint>();
        return Names.TryGetValue(name.Trim(), out var ids) ? ids : Array.Empty<uint>();
    }

